// Shared with the Swift tests (Tests/fixtures, generated by scripts/generate-fixtures.py).
const fixture = <T>(name: string): T =>
  JSON.parse(readFileSync(join(__dirname, "..", "..", "Tests", "fixtures", name), "utf8")) as T;
const near = (a: number, b: number, tolerance = 1e-9, label = "") =>
  assert.ok(Math.abs(a - b) <= tolerance, `${label} ${a} != ${b} (±${tolerance})`);
const nearAll = (a: number[], b: number[], tolerance = 1e-9, label = "") =>
  a.forEach((value, i) => near(value, b[i], tolerance, `${label}[${i}]`));
const angleDeg = (a: Vec3, b: Vec3) =>
  (Math.acos(Math.min(1, Math.abs(dot(a, b)) / Math.hypot(...a) / Math.hypot(...b))) * 180) / Math.PI;

test("mulberry32 matches the shared sequence", () => {
  const { seed, values } = fixture<{ seed: number; values: number[] }>("prng.json");
  const random = mulberry32(seed);
  values.forEach((value) => near(random(), value, 1e-11));
});

test("Jacobi eigen-decomposition satisfies A v = lambda v", () => {
  const A = [[4, 1, 0.5], [1, 3, 0.2], [0.5, 0.2, 1]];
  const { values, vectors } = symmetricEigen(A);
  assert.ok(values[0] <= values[1] && values[1] <= values[2]);
  vectors.forEach((v, k) => {
    const Av = A.map((row) => row[0] * v[0] + row[1] * v[1] + row[2] * v[2]);
    nearAll(Av, v.map((x) => x * values[k]), 1e-10);
  });
});

type YawCase = { name: string; position: Vec3; normal: Vec3; camera: Vec3; heading: Vec3; x: Vec3; y: Vec3; z: Vec3; alongRowInclination: number; crossSlope: number; matrix: number[] };
test("yaw from latched horizontal heading, inclination from floor (plan section 3)", () => {
  const { cases, rejects, tolerance } = fixture<{ cases: YawCase[]; rejects: YawCase[]; tolerance: number }>("yaw_cases.json");
  for (const c of cases) {
    const heading = horizontalHeading(c.position, c.camera)!;
    nearAll(heading, c.heading, tolerance, c.name);
    const frame = rowFrame(c.position, c.normal, heading)!;
    nearAll(frame.matrix, c.matrix, 1e-9, c.name);
    near(frame.alongRowInclination, c.alongRowInclination, 1e-9, c.name);
    near(frame.crossSlope, c.crossSlope, 1e-9, c.name);
    // The long edge's plan-view projection stays perpendicular to the heading.
    const x = frame.matrix.slice(0, 3) as Vec3;
    near(x[0] * heading[0] + x[2] * heading[2], 0, 1e-12, c.name);
    const pose = surfacePose(c.position, c.normal, c.camera)!;
    nearAll(pose.matrix, c.matrix, 1e-9, c.name);
    // Changing camera height/downward angle at the same location never tilts the row.
    const lower = surfacePose(c.position, c.normal, [c.camera[0], c.position[1] + 0.4, c.camera[2]])!;
    nearAll(lower.matrix, c.matrix, 1e-9, `${c.name} camera height`);
  }
  for (const c of rejects) assert.equal(surfacePose(c.position, c.normal, c.camera), null, c.name);
});

type PlaneCase = {
  name: string; origin: Vec3; heading: Vec3; gravityUp: Vec3; epoch: number;
  observations: SurfaceObservation[]; trueNormal: Vec3; trueAlongRowInclination: number;
  physicalAlongRowInclination?: number;
  expect: { status: string[]; normalToleranceDeg?: number; source?: string; batches?: number };
};
test("robust floor fit recovers pitched/compound planes and rejects bad support", () => {
  for (const c of fixture<{ cases: PlaneCase[] }>("plane_fit_cases.json").cases) {
    const result = fitFloor({ observations: c.observations, origin: c.origin, heading: c.heading, gravityUp: c.gravityUp, epoch: c.epoch });
    assert.ok(c.expect.status.includes(result.status), `${c.name}: ${result.status} ${result.reasons.join(", ")}`);
    if (c.expect.normalToleranceDeg !== undefined) {
      assert.ok(result.normal, c.name);
      assert.ok(angleDeg(result.normal!, c.trueNormal) <= c.expect.normalToleranceDeg, `${c.name}: ${angleDeg(result.normal!, c.trueNormal)}`);
      near(result.alongRowInclination!, c.trueAlongRowInclination, c.expect.normalToleranceDeg, c.name);
    }
    if (c.expect.source) assert.equal(result.source, c.expect.source, c.name);
    if (c.expect.batches) assert.equal(result.batches, c.expect.batches, c.name);
    assert.ok(result.limitations.some((l) => l.startsWith("precision unverified")));
    if (c.physicalAlongRowInclination !== undefined) {
      // Low residuals and narrow intervals do not detect an absolute bias.
      assert.ok(Math.abs(result.alongRowInclination! - c.physicalAlongRowInclination) > 0.2, c.name);
      assert.ok((result.robustResidualM ?? 1) < 0.01, c.name);
    }
  }
});

test("calibration is deterministic", () => {
  const c = fixture<{ cases: PlaneCase[] }>("plane_fit_cases.json").cases[1];
  const a = fitFloor({ ...c });
  const b = fitFloor({ ...c });
  assert.deepEqual(a, b);
});

type BudgetCase = { width: number; count: number; radiusM: number; verticalAngleAllowanceDeg: number; horizontalRotationAllowanceDeg: number };
test("accuracy budget follows the actual farthest rendered vertex", () => {
  const { cases, displacement } = fixture<{ cases: BudgetCase[]; displacement: { errorDeg: number; radiusM: number; displacementM: number }[] }>("budget_cases.json");
  for (const c of cases) {
    const budget = accuracyBudget(c.width, c.count);
    near(budget.radiusM, c.radiusM, 1e-9);
    near(budget.verticalAngleAllowanceDeg, c.verticalAngleAllowanceDeg, 1e-9);
    near(budget.horizontalRotationAllowanceDeg, c.horizontalRotationAllowanceDeg, 1e-9);
  }
  for (const d of displacement) near(rotationDisplacementM(d.errorDeg, d.radiusM), d.displacementM, 1e-9);
  assert.ok(accuracyBudget(3, 15).radiusM > 22.5);
});

type HeightFixture = {
  base: number[]; gravityUp: Vec3;
  steps: { time: number; observations: HeightObservation[]; apply: boolean; expectedResidualCount: number; expectedRejected: number; expectedProposedM: number | null; expectedAppliedM: number }[];
};
test("gated height correction: gravity residuals, gates, rate limit and mode isolation", () => {
  const f = fixture<HeightFixture>("height_correction_cases.json");
  const applied = new HeightCorrector();
  const shadow = new HeightCorrector();
  for (const step of f.steps) {
    const update = applied.update(f.base, step.observations, step.time, true);
    assert.equal(update.residuals.length, step.expectedResidualCount);
    assert.equal(update.rejected.length, step.expectedRejected);
    if (step.expectedProposedM === null) assert.equal(update.proposedDeltaM, null);
    else near(update.proposedDeltaM!, step.expectedProposedM, 1e-9);
    near(update.appliedDeltaM, step.expectedAppliedM, 1e-9);
    // Shadow (surveyed/baseline/calibrated modes) never applies an offset.
    assert.equal(shadow.update(f.base, step.observations, step.time, false).appliedDeltaM, 0);
  }
  near(gravityResidual(f.base, [f.base[12], f.base[13] + 0.03, f.base[14]])!, 0.03, 1e-12);
  const corrected = correctedWorldFromRow(f.base, 0.03);
  nearAll(corrected.slice(0, 12), f.base.slice(0, 12), 1e-15);
  near(corrected[13] - f.base[13], 0.03, 1e-12);
  // Loss stops updates; a reset (new commit / mode change) clears offsets.
  applied.markStale();
  const held = applied.update(f.base, [], 99, true);
  assert.ok(held.stale);
  near(held.appliedDeltaM, f.steps.at(-1)!.expectedAppliedM, 1e-9);
  applied.reset();
  assert.equal(applied.appliedDeltaM, 0);
});

type SurveyCase = { name: string; manifest: unknown; ok: boolean; error?: string; floorNormal?: Vec3 };
test("survey import rejects ambiguous geometry", () => {
  for (const c of fixture<{ cases: SurveyCase[] }>("survey_manifests.json").cases) {
    const result = validateSurvey(c.manifest);
    assert.equal(result.ok, c.ok, `${c.name}: ${result.ok ? "" : result.errors.join(",")}`);
    if (!result.ok) assert.ok(result.errors.includes(c.error!), `${c.name}: ${result.errors.join(",")}`);
    else assert.ok(angleDeg(result.manifest.floor.normal, c.floorNormal!) < 1e-6);
  }
});

type FusionCase = {
  name: string; observations: MarkerObservation[]; now: number; epoch: number; expected: number[] | null;
  used: string[]; rejected?: string[]; observability: string; toleranceM?: number; toleranceDeg?: number; validation?: Record<string, number>;
};
test("one rigid world-from-survey fusion with outlier, staleness and held-out handling", () => {
  const f = fixture<{ manifest: unknown; worldFromSurvey: number[]; cases: FusionCase[] }>("fusion_cases.json");
  const manifest = (validateSurvey(f.manifest) as { ok: true; manifest: SurveyManifest }).manifest;
  for (const c of f.cases) {
    const result = fuseReferences(manifest, c.observations, c.now, c.epoch);
    assert.deepEqual(result.used, c.used, c.name);
    assert.equal(result.observability, c.observability, c.name);
    if (c.rejected) assert.deepEqual([...new Set(result.rejected.map((r) => r.id))].sort(), c.rejected, c.name);
    if (c.expected === null) assert.equal(result.worldFromSurvey, null, c.name);
    else {
      const d = poseDifference(result.worldFromSurvey!, c.expected);
      assert.ok(d.positionM <= c.toleranceM! && d.rotationDeg <= c.toleranceDeg!, `${c.name}: ${JSON.stringify(d)}`);
    }
    for (const [id, positionM] of Object.entries(c.validation ?? {}))
      near(result.validation.find((v) => v.id === id)!.positionM, positionM, 1e-9, c.name);
  }
});

test("survey controller: floor authority, one root, phone offset never applied", () => {
  const f = fixture<{ manifest: unknown; worldFromSurvey: number[]; cases: FusionCase[] }>("fusion_cases.json");
  const manifest = (validateSurvey(f.manifest) as { ok: true; manifest: SurveyManifest }).manifest;
  const controller = new ReferenceFrameController(manifest);
  f.cases[1].observations.forEach((o) => controller.observe(o));
  assert.equal(controller.update(10.1, 1, null), "tracking");
  const surveyHit: Vec3 = [3, 3 * Math.tan((1.5 * Math.PI) / 180) + 0.2, 0.3];
  const placed = controller.placeRow(
    [0, 1, 2].map((r) => f.worldFromSurvey[12 + r] + f.worldFromSurvey[r] * surveyHit[0] + f.worldFromSurvey[4 + r] * surveyHit[1] + f.worldFromSurvey[8 + r] * surveyHit[2]) as Vec3,
    [0, 1, 2].map((r) => f.worldFromSurvey[12 + r] + f.worldFromSurvey[r] * 3 + f.worldFromSurvey[4 + r] * 1.8 + f.worldFromSurvey[8 + r] * 2.5) as Vec3,
  );
  assert.ok("surveyFromRow" in placed);
  // The committed floor normal is the surveyed one, not the phone's.
  nearAll(placed.surveyFromRow.slice(4, 7), manifest.floor.normal, 1e-12);
  // The origin lies on the surveyed floor plane even though the phone hit was 20 cm high.
  const origin = placed.surveyFromRow.slice(12, 15) as Vec3;
  near(dot(manifest.floor.normal, origin.map((v, i) => v - manifest.floor.point[i]) as Vec3), 0, 1e-9);
  controller.commit(placed.surveyFromRow, null);
  const root = controller.worldFromRow()!;
  nearAll(root, multiply(f.worldFromSurvey, placed.surveyFromRow), 1e-9);
  // Out of the surveyed extent is rejected rather than extrapolated.
  const far = controller.placeRow([100, 0, 100], [100, 1.6, 102]);
  assert.ok("error" in far);
  // Losing every board keeps the last mapping but reports it as stale.
  assert.equal(controller.update(20, 1, null), "stale");
});

type TransportFixture = {
  hit: number[]; anchor: number[]; anchorPosition: Vec3; anchorQuaternion: number[]; placed: number[];
  referenceFromRow: number[]; updates: number[][]; rendered: number[][]; naiveFirstRender: number[];
};
test("actual-anchor baseline: first render preserves placement and updates move one rigid root", () => {
  const f = fixture<TransportFixture>("transport_cases.json");
  const anchor = anchorMatrix(f.anchorPosition, f.anchorQuaternion)!;
  assert.equal(anchor.format, "quaternion");
  nearAll(anchor.matrix, f.anchor, 1e-9);
  const referenceFromRow = multiply(inverseRigid(anchor.matrix), f.placed);
  nearAll(referenceFromRow, f.referenceFromRow, 1e-9);
  nearAll(multiply(anchor.matrix, referenceFromRow), f.placed, 1e-9);
  f.updates.forEach((update, i) => nearAll(multiply(update, referenceFromRow), f.rendered[i], 1e-9));
  // Using the hit as the baseline (the old behaviour) visibly jumps.
  assert.ok(poseDifference(f.naiveFirstRender, f.placed).positionM > 0.01);
  // Euler callbacks still convert through the Viro convention.
  const euler = anchorMatrix([1, 2, 3], [10, 20, 30])!;
  assert.equal(euler.format, "euler");
  nearAll(euler.matrix, transformMatrix([1, 2, 3], [10, 20, 30]), 1e-12);
});
